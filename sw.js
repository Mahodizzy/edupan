/* EduPan · trabajador de la app instalable.
   Primero intenta la red (así cada actualización se ve al instante) y, si no hay
   internet, muestra la última copia guardada de la página. Los datos NO se guardan
   aquí: siempre vienen de Firebase. */
const CACHE = "edupan-v1";
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return; // Firebase y Google van directo
  e.respondWith(
    fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match(req).then((r) => r || caches.match("./")))
  );
});
